import cv2
import numpy as np
import matplotlib.pyplot as plt
import random

def add_salt_and_pepper_noise(image, salt_prob, pepper_prob):
    noisy = np.copy(image)
    # Salt noise
    num_salt = np.ceil(salt_prob * image.size)
    coords = [np.random.randint(0, i - 1, int(num_salt)) for i in image.shape]
    noisy[tuple(coords)] = 255

    # Pepper noise
    num_pepper = np.ceil(pepper_prob * image.size)
    coords = [np.random.randint(0, i - 1, int(num_pepper)) for i in image.shape]
    noisy[tuple(coords)] = 0
    return noisy

A = cv2.imread('/content/images (1).jpg', 0)
if A is None:
    print("Error: Image not found.")
else:
    # Add Salt & Pepper Noise
    noisy_img = add_salt_and_pepper_noise(A, 0.05, 0.05)

    # Apply Filters
    median_filter = cv2.medianBlur(noisy_img, 3)
    gaussian_filter = cv2.GaussianBlur(noisy_img, (3, 3), 0)

    # Plot Results
    plt.figure(figsize=(15, 5))

    plt.subplot(1, 3, 1)
    plt.imshow(noisy_img, cmap='gray')
    plt.title("Salt & Pepper Noisy Input")
    plt.axis('off')

    plt.subplot(1, 3, 2)
    plt.imshow(median_filter, cmap='gray')
    plt.title("Median Filter")
    plt.axis('off')

    plt.subplot(1, 3, 3)
    plt.imshow(gaussian_filter, cmap='gray')
    plt.title("Gaussian Filter")
    plt.axis('off')

    plt.tight_layout()
    plt.show()